# /// script
# requires-python = ">=3.12"
# dependencies = ["marimo==0.25.2", "pyyaml"]
# ///
"""Turn every marimo notebook under src/content/docs/ into a page beside it.

    uv run scripts/docs/notebook_pages.py

`x.py` gets `x.mdx` or `x.md`, depending on its page mode in sources.yaml:

- islands (the default): `x.mdx` from `marimo export md --flavor mdx`. mdx-marimo
  runs the cells once at build time and again in the reader's browser, through
  Pyodide. Every cell that shows its code in marimo gets an editable code cell.
- static: `x.md` with the notebook's text and code. Nothing runs, at build time or
  in the browser, so it suits notebooks that need data or packages a reader lacks.
  Cells that hide their code in marimo become closed folds.

Every page also gets:

- its title: the link text its tutorial page gives it, else the H1 it opens with,
  else marimo's title. An opening H1 is dropped, as the title shows it.
- an "Edit page" link to the notebook, upstream for notebooks from sources.yaml.
- in a tutorial, a "Part n of N" line and that place in the sidebar. A tutorial is
  a page with `tutorial: <name>` in its front matter; the .py links under its
  `## <name>` heading, in order, are its parts.

Pages are written only when their content changed. A generated page whose notebook
is gone is deleted. Never edit a generated page: edit the notebook and rerun.
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "src" / "content" / "docs"
REPO = "bedrock-engineer/bedrock-docs"
MARKER = "# Generated by scripts/docs/notebook_pages.py"
FRONT_MATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
PY_LINK = re.compile(r"\[([^\]]+)\]\(([^)#\s]+\.py)\)")
LEADING_H1 = re.compile(r"\A\s*# (.+)\n")
CONFIG_FENCE = re.compile(r"\A\s*```marimo-config\n.*?\n```\n", re.S)
COMMENT_CELL = re.compile(r"\A\s*```python marimo include=false\n(?:#[^\n]*\n)+```\n")
MARIMO_FENCE = re.compile(r"^```(python|sql|markdown) marimo(.*)$", re.M)
CELL = re.compile(r"^```(python|sql) marimo(.*?)\n(.*?)^```$", re.S | re.M)


class Literal(str):
    pass


yaml.SafeDumper.add_representer(
    Literal, lambda dumper, value: dumper.represent_scalar("tag:yaml.org,2002:str", value, style="|")
)


def split(text: str) -> tuple[dict, str]:
    match = FRONT_MATTER.match(text)
    if not match:
        return {}, text
    return yaml.safe_load(match.group(1)) or {}, text[match.end() :]


def load_sources() -> dict[Path, dict]:
    """sources.yaml's entry for each notebook it lists or whose folder it copies."""
    entries = yaml.safe_load((ROOT / "sources.yaml").read_text(encoding="utf-8")) or []
    by_notebook: dict[Path, dict] = {}
    for entry in entries:
        folder = (DOCS / entry["to"]).resolve()
        pairs: list[tuple[str, str]] = []
        for item in entry.get("files") or [p.relative_to(folder).as_posix() for p in folder.rglob("*.py")]:
            pairs.extend(item.items() if isinstance(item, dict) else [(item, item)])
        for upstream, name in pairs:
            by_notebook[(folder / name).resolve()] = {**entry, "name": upstream}
    return by_notebook


def find_tutorials() -> dict[Path, dict]:
    tutorials: dict[Path, dict] = {}
    for page in sorted(DOCS.rglob("*.md*")):
        meta, body = split(page.read_text(encoding="utf-8"))
        name = meta.get("tutorial")
        if not name:
            continue
        section = re.search(rf"^## {re.escape(name)}\n(.*?)(?=^## |\Z)", body, re.S | re.M)
        parts: dict[Path, str] = {}
        for text, href in PY_LINK.findall(section.group(1) if section else ""):
            parts.setdefault((page.parent / href).resolve(), text.strip("*`_ "))
        for position, (notebook, text) in enumerate(parts.items(), 1):
            tutorials[notebook] = {
                "page": page,
                "name": name,
                "position": position,
                "total": len(parts),
                "link_text": text,
            }
    return tutorials


def export(notebook: Path) -> str:
    result = subprocess.run(
        [sys.executable, "-m", "marimo", "export", "md", "--flavor", "mdx", str(notebook)],
        capture_output=True,
        encoding="utf-8",
        env={**os.environ, "PYTHONIOENCODING": "utf-8"},
        check=True,
    )
    return result.stdout


def in_prose(body: str, pattern: str, replacement: str) -> str:
    """Substitute in the Markdown between code fences only."""
    parts = re.split(r"(^```.*?^```$)", body, flags=re.S | re.M)
    for index in range(0, len(parts), 2):
        parts[index] = re.sub(pattern, replacement, parts[index], flags=re.S | re.M)
    return "".join(parts)


def editable(body: str) -> str:
    """Islands: an editable code cell for every cell that shows its code in marimo."""

    def fence(match: re.Match) -> str:
        options = match.group(2)
        if "hide-code=true" in options or "include=false" in options or "editor=" in options:
            return match.group(0)
        return f"```{match.group(1)} marimo editor=true{options}"

    return MARIMO_FENCE.sub(fence, body)


def as_code(body: str) -> str:
    """Static: plain code blocks; a cell that hides its code becomes a closed fold."""

    def cell(match: re.Match) -> str:
        language, options, code = match.groups()
        if "include=false" in options:
            return ""
        block = f"```{language}\n{code}```"
        if "hide-code=true" not in options:
            return block
        name = re.search(r"name=(\S+)", options)
        label = f"Hidden cell: <code>{name.group(1)}</code>" if name else "Hidden cell"
        return (
            '<details class="group">\n'
            f'<summary class="cursor-pointer text-sm text-doc-muted group-open:mb-2">{label}</summary>\n\n'
            f"{block}\n\n</details>"
        )

    return CELL.sub(cell, body)


def relative(target: Path, start: Path) -> str:
    return Path(os.path.relpath(target, start.parent)).as_posix()


def edit_url(notebook: Path, source: dict | None) -> str:
    if source and source.get("repo"):
        folder = source["from"].strip("/")
        return f"https://github.com/{source['repo']}/edit/{source.get('branch', 'main')}/{folder}/{source['name']}"
    return f"https://github.com/{REPO}/edit/main/{notebook.relative_to(ROOT).as_posix()}"


def view_url(notebook: Path, source: dict | None) -> str:
    if source and source.get("repo"):
        folder = source["from"].strip("/")
        return f"https://github.com/{source['repo']}/blob/{source['rev']}/{folder}/{source['name']}"
    return f"https://github.com/{REPO}/blob/main/{notebook.relative_to(ROOT).as_posix()}"


def page(notebook: Path, source: dict | None, tutorial: dict | None) -> tuple[str, str]:
    """The page for `notebook`, and its file extension."""
    mode = (source or {}).get("mode", "islands")
    meta, body = split(export(notebook))
    config = ""
    match = CONFIG_FENCE.match(body)
    if match:
        config, body = match.group(0).strip("\n"), body[match.end() :]
    body = COMMENT_CELL.sub("", body)

    title = meta.get("title") or notebook.stem
    h1 = LEADING_H1.match(body)
    if h1:
        title, body = h1.group(1).strip(), body[h1.end() :]
    if tutorial:
        title = tutorial["link_text"]

    glossary = relative(DOCS / "reference" / "glossary.md", notebook)
    intro = []
    if tutorial:
        intro.append(
            f"*Part {tutorial['position']} of {tutorial['total']} in "
            f"[{tutorial['name']}]({relative(tutorial['page'], notebook)}).*"
        )
    if mode == "static":
        intro.append(
            ":::note[Static notebook page]\n"
            f"This page shows the notebook's text and code. It is [static]({glossary}#page-mode): "
            "nothing runs, so its outputs, sliders and buttons aren't here. "
            f"[See the notebook on GitHub]({view_url(notebook, source)}).\n:::"
        )
        body, config, extension = as_code(body), "", ".md"
    else:
        # marimo's mdx export leaves HTML comments in prose, which MDX rejects.
        body, extension = in_prose(editable(body), r"<!--(.*?)-->", r"{/*\1*/}"), ".mdx"

    front: dict = {"title": title, "editUrl": edit_url(notebook, source)}
    if tutorial:
        front["sidebar"] = {"order": tutorial["position"]}
    head = (
        f"---\n{MARKER} from {notebook.name}.\n# Edit the notebook, then run `just pages`.\n"
        + yaml.safe_dump(front, allow_unicode=True, sort_keys=False)
        + "---\n\n"
    )
    parts = [config, "\n\n".join(intro), body.lstrip("\n")]
    return head + "\n\n".join(part.strip("\n") for part in parts if part.strip()) + "\n", extension


def is_notebook(path: Path) -> bool:
    return "marimo.App(" in path.read_text(encoding="utf-8")


def main() -> None:
    sources, tutorials = load_sources(), find_tutorials()
    notebooks = [p for p in sorted(DOCS.rglob("*.py")) if "__marimo__" not in p.parts and is_notebook(p)]
    wanted: set[Path] = set()
    for notebook in notebooks:
        text, extension = page(notebook, sources.get(notebook.resolve()), tutorials.get(notebook.resolve()))
        out = notebook.with_suffix(extension)
        wanted.add(out)
        if out.exists() and out.read_text(encoding="utf-8") == text:
            continue
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"{notebook.relative_to(DOCS).as_posix()} -> {out.name}")
    for stale in sorted([*DOCS.rglob("*.md"), *DOCS.rglob("*.mdx")]):
        if stale not in wanted and stale.read_text(encoding="utf-8").startswith(f"---\n{MARKER}"):
            stale.unlink()
            print(f"removed {stale.relative_to(DOCS).as_posix()}")


if __name__ == "__main__":
    main()
