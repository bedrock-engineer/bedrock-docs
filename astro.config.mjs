import { remarkObsidianCallouts } from "./src/plugins/remark-obsidian-callouts.mjs";

// The site lives under /bedrock-docs/ on GitHub Pages; pages never write the base
// themselves (src/plugins/remark-glossary.mjs adds it to every root-relative link).
const BASE = "/bedrock-docs";
const contentDir = fileURLToPath(new URL("./src/content/docs/", import.meta.url));
const glossary = [remarkGlossary, { base: BASE, contentDir, glossaryFile: contentDir + "reference/glossary.md" }];
// marimo cells only in .mdx: marimo turns ```python marimo fences into MDX islands.
const mdxOnly = (plugin) => (options) => {
  const transform = plugin(options);
  return (tree, file) => (file.path?.endsWith(".mdx") ? transform(tree, file) : undefined);
};
const remarkPlugins = [remarkMath, remarkObsidianCallouts, glossary, mdxOnly(remarkMarimo)];
// Pandoc citations, [@citekey] or [@citekey, 1.5.2.4], against bibliography.json, the
// CSL-JSON export of the cited Library items. Before rehypeHeadingIds, so the
// "References" heading rehypeCitationCards adds gets an id and a place in the TOC.
const citations = [rehypeCitation, {
  path: fileURLToPath(new URL("./", import.meta.url)),
  bibliography: "bibliography.json",
  csl: "src/plugins/citation-style.csl",
  linkCitations: true,
  showTooltips: true,
  tooltipAttribute: "data-citation",
}];
const rehypePlugins = [citations, rehypeCitationCards, rehypeHeadingIds, rehypeKatex];
const glossaryScript = readFileSync(new URL("./src/scripts/glossary.js", import.meta.url), "utf8");

// mdx-marimo runs uv to compile the marimo cells. Without this it picks the uv of the
// @manzt/uv npm package, whose install script pnpm skips; on Windows it would also spawn
// node_modules/.bin/uv.cmd without a shell, which Node refuses (spawn EINVAL).
process.env.MDX_MARIMO_UV ??= "uv";

// Every sidebar group starts collapsed, nested and autogenerated ones included;
// Starlight still opens the group that holds the current page.
const collapseEveryGroup = (entries) =>
  entries.map((entry) => {
    if (entry.autogenerate) {
      return { ...entry, autogenerate: { ...entry.autogenerate, collapsed: true } };
    }
    if (entry.items) {
      return { ...entry, collapsed: true, items: collapseEveryGroup(entry.items) };
    }
    return entry;
  });

// https://astro.build/config
